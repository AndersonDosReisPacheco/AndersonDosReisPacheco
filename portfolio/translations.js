let currentLanguage = "pt-BR";

function getLanguageLabel(lang) {
  const labels = {
    "pt-BR": "PT",
    "en-US": "EN",
    "en-GB": "UK",
    "es-ES": "ES",
    "fr-FR": "FR",
    "de-DE": "DE"
  };
  return labels[lang] || lang.split("-")[0].toUpperCase();
}

function changeLanguage(lang) {
  if (!translations[lang]) {
    console.error(`❌ Idioma não suportado: ${lang}`);
    return;
  }

  currentLanguage = lang;
  console.log(`🌐 Idioma alterado para: ${lang}`);
  document.documentElement.lang = lang;

  updateAllTexts();
  saveLanguagePreference(lang);
  updateActiveLanguageButton();

  document.dispatchEvent(new CustomEvent("languageChanged", { detail: { language: lang } }));
}

function updateAllTexts() {
  const langData = translations[currentLanguage];
  if (!langData) return;

  const elements = document.querySelectorAll("[data-i18n]");
  console.log(`📝 Atualizando ${elements.length} elementos`);

  elements.forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (langData[key]) {
      if (langData[key].includes("<")) {
        element.innerHTML = langData[key];
      } else {
        element.textContent = langData[key];
      }
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.getAttribute("data-i18n-placeholder");
    if (langData[key]) element.placeholder = langData[key];
  });

  document.querySelectorAll("[data-i18n-title]").forEach((element) => {
    const key = element.getAttribute("data-i18n-title");
    if (langData[key]) element.title = langData[key];
  });

  window.currentLanguage = currentLanguage;
  document.title = langData.site_title || "Anderson Pacheco | Portfolio";
  updateFilterButtons(langData);
}

function updateFilterButtons(langData) {
  document.querySelectorAll(".filter-btn").forEach((btn) => {
    const filter = btn.getAttribute("data-filter");
    const keyMap = {
      all: "all_projects",
      fullstack: "fullstack_projects",
      backend: "backend_projects"
    };
    const key = keyMap[filter];
    if (key && langData[key]) btn.textContent = langData[key];
  });
}

function saveLanguagePreference(lang) {
  try {
    localStorage.setItem("portfolio-language", lang);
  } catch (e) {}
}

function loadLanguagePreference() {
  try {
    const savedLang = localStorage.getItem("portfolio-language");
    if (savedLang && translations[savedLang]) {
      currentLanguage = savedLang;
      return;
    }
  } catch (e) {}

  const browserLang = navigator.language || navigator.userLanguage;
  if (browserLang.startsWith("pt")) currentLanguage = "pt-BR";
  else if (browserLang.startsWith("en")) currentLanguage = browserLang.includes("GB") ? "en-GB" : "en-US";
  else if (browserLang.startsWith("es")) currentLanguage = "es-ES";
  else if (browserLang.startsWith("fr")) currentLanguage = "fr-FR";
  else if (browserLang.startsWith("de")) currentLanguage = "de-DE";

  window.currentLanguage = currentLanguage;
}

function updateActiveLanguageButton() {
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const lang = btn.getAttribute("data-lang");
    if (lang === currentLanguage) btn.classList.add("active");
    else btn.classList.remove("active");
  });

  const toggleSpan = document.querySelector(".language-toggle span");
  if (toggleSpan) {
    toggleSpan.textContent = getLanguageLabel(currentLanguage);
  }
}

window.changeLanguage = changeLanguage;
window.updateAllTexts = updateAllTexts;
window.loadLanguagePreference = loadLanguagePreference;
window.updateActiveLanguageButton = updateActiveLanguageButton;
window.currentLanguage = currentLanguage;

